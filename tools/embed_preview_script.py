"""Regenerates CK_PreviewScript.h from tools/ck_preview_server.py.

Run after editing the server script:  python tools/embed_preview_script.py
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "ck_preview_server.py")
dst = os.path.join(os.path.dirname(here), "CK_PreviewScript.h")

text = open(src, encoding="utf-8").read().replace("\r\n", "\n")
assert ")CKPY" not in text
# MSVC caps a single string literal at ~16 KB: emit several and let the
# compiler join them.
parts = [text[i:i + 12000] for i in range(0, len(text), 12000)]
with open(dst, "w", encoding="utf-8", newline="\r\n") as f:
    f.write("// Generated by tools/embed_preview_script.py from tools/ck_preview_server.py.\n")
    f.write("// Do not edit by hand.\n#pragma once\n\n")
    f.write("static const char* const kCK_PreviewScript =\n")
    for p in parts:
        f.write('R"CKPY(' + p + ')CKPY"\n')
    f.write(";\n")
print("wrote", dst)
