"""Regenerates the embedded Python scripts:
  CK_PreviewScript.h  from tools/ck_preview_server.py
  CK_InferScript.h    from tools/ck_infer_scaled.py

Run after editing either script:  python tools/embed_preview_script.py
"""
import os

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)


def embed(src_name, dst_name, var):
    text = open(os.path.join(here, src_name), encoding="utf-8").read().replace("\r\n", "\n")
    assert ")CKPY" not in text
    # MSVC caps a single string literal at ~16 KB: emit several and let the
    # compiler join them.
    parts = [text[i:i + 12000] for i in range(0, len(text), 12000)]
    dst = os.path.join(root, dst_name)
    with open(dst, "w", encoding="utf-8", newline="\r\n") as f:
        f.write("// Generated by tools/embed_preview_script.py from tools/%s.\n" % src_name)
        f.write("// Do not edit by hand.\n#pragma once\n\n")
        f.write("static const char* const %s =\n" % var)
        for p in parts:
            f.write('R"CKPY(' + p + ')CKPY"\n')
        f.write(";\n")
    print("wrote", dst)


embed("ck_preview_server.py", "CK_PreviewScript.h", "kCK_PreviewScript")
embed("ck_infer_scaled.py", "CK_InferScript.h", "kCK_InferScript")
